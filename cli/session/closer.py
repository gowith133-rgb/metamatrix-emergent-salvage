"""
Metamatrix Session Closer
Auto-documentation protocol: summarize → log → commit.
"""

from __future__ import annotations

import os
import json
import subprocess
from pathlib import Path
from datetime import datetime
from typing import List, Dict, Any, Optional

# Session log directory
SESSIONS_DIR = Path.home() / ".metamatrix" / "sessions"


def _ensure_sessions_dir():
    SESSIONS_DIR.mkdir(parents=True, exist_ok=True)


def summarize_session(messages: List[Dict[str, Any]]) -> str:
    """
    Generate a session summary from message history.

    Args:
        messages: List of {"role": str, "content": str, "timestamp": str} dicts

    Returns:
        Markdown-formatted session summary string
    """
    if not messages:
        return "## Session Summary\n\nNo messages recorded in this session."

    now = datetime.now()
    user_msgs = [m for m in messages if m.get("role", "").lower() in ("user", "human")]
    ai_msgs = [m for m in messages if m.get("role", "").lower() in ("assistant", "ai", "node")]

    # Extract topics from user messages
    topics = []
    for msg in user_msgs[:10]:  # First 10 user messages for topic extraction
        content = msg.get("content", "").strip()
        if content:
            # Take first 80 chars as topic hint
            topics.append(content[:80] + ("..." if len(content) > 80 else ""))

    # Build summary
    lines = [
        f"# Session Log — {now.strftime('%Y-%m-%d %H:%M')}",
        "",
        "## Overview",
        f"- **Messages**: {len(messages)} total ({len(user_msgs)} user, {len(ai_msgs)} node)",
        f"- **Duration**: {_estimate_duration(messages)}",
        f"- **Session date**: {now.strftime('%Y-%m-%d')}",
        f"- **Session time**: {now.strftime('%H:%M:%S')}",
        "",
        "## Topics Discussed",
    ]

    for i, topic in enumerate(topics[:5], 1):
        lines.append(f"{i}. {topic}")

    if not topics:
        lines.append("*No topics recorded.*")

    lines.extend([
        "",
        "## First Exchange",
    ])

    if messages:
        first = messages[0]
        lines.append(f"**{first.get('role', 'user').capitalize()}**: {first.get('content', '')[:200]}")

    lines.extend([
        "",
        "## Last Exchange",
    ])

    if len(messages) > 1:
        last = messages[-1]
        lines.append(f"**{last.get('role', 'node').capitalize()}**: {last.get('content', '')[:200]}")

    lines.extend([
        "",
        "## Raw Message Count",
        f"Total tokens (estimated): ~{_estimate_tokens(messages)}",
        "",
        "---",
        f"*Generated by Metamatrix Session Closer — {now.isoformat()}*",
    ])

    return "\n".join(lines)


def _estimate_duration(messages: List[Dict[str, Any]]) -> str:
    """Estimate session duration from message timestamps."""
    timestamps = []
    for m in messages:
        ts = m.get("timestamp")
        if ts:
            try:
                timestamps.append(datetime.fromisoformat(ts))
            except Exception:
                pass

    if len(timestamps) >= 2:
        delta = timestamps[-1] - timestamps[0]
        minutes = int(delta.total_seconds() / 60)
        if minutes < 60:
            return f"{minutes} minutes"
        hours = minutes // 60
        mins = minutes % 60
        return f"{hours}h {mins}m"

    return "unknown"


def _estimate_tokens(messages: List[Dict[str, Any]]) -> int:
    """Rough token estimate (1 token ≈ 4 chars)."""
    total_chars = sum(len(m.get("content", "")) for m in messages)
    return total_chars // 4


def write_session_log(summary: str, path: Optional[str] = None) -> str:
    """
    Write the session summary to a dated .md file.

    Args:
        summary: Markdown session summary string
        path: Optional custom file path

    Returns:
        Path to the written file
    """
    _ensure_sessions_dir()

    if path:
        dest = Path(path)
        dest.parent.mkdir(parents=True, exist_ok=True)
    else:
        date_str = datetime.now().strftime("%Y-%m-%d")
        dest = SESSIONS_DIR / f"{date_str}.md"

        # Handle multiple sessions per day
        if dest.exists():
            counter = 1
            while dest.exists():
                dest = SESSIONS_DIR / f"{date_str}_{counter:02d}.md"
                counter += 1

    dest.write_text(summary, encoding="utf-8")
    return str(dest)


def git_commit_session(repo_path: str, message: str = "", session_log_path: str = "") -> Dict[str, Any]:
    """
    Add and commit the session log to a git repository.

    Args:
        repo_path: Path to the git repository
        message: Commit message (auto-generated if empty)
        session_log_path: Path to session log file to add

    Returns:
        dict with success status and output
    """
    repo = Path(repo_path).resolve()

    if not (repo / ".git").exists():
        return {
            "success": False,
            "error": f"Not a git repository: {repo}",
        }

    if not message:
        message = f"session: auto-log {datetime.now().strftime('%Y-%m-%d %H:%M')}\n\nMetamatrix session closer protocol."

    results = {}

    # git add
    add_targets = []
    if session_log_path and Path(session_log_path).exists():
        add_targets.append(session_log_path)
    else:
        add_targets.append(".")

    for target in add_targets:
        try:
            result = subprocess.run(
                ["git", "add", target],
                cwd=str(repo),
                capture_output=True,
                text=True,
                timeout=30,
            )
            results["add"] = {"returncode": result.returncode, "stdout": result.stdout, "stderr": result.stderr}
        except subprocess.TimeoutExpired:
            return {"success": False, "error": "git add timed out"}
        except Exception as e:
            return {"success": False, "error": f"git add failed: {e}"}

    # Check if there's anything to commit
    try:
        status_result = subprocess.run(
            ["git", "status", "--porcelain"],
            cwd=str(repo),
            capture_output=True,
            text=True,
            timeout=10,
        )
        if not status_result.stdout.strip():
            return {"success": True, "message": "Nothing to commit.", "results": results}
    except Exception:
        pass

    # git commit
    try:
        result = subprocess.run(
            ["git", "commit", "-m", message],
            cwd=str(repo),
            capture_output=True,
            text=True,
            timeout=30,
        )
        results["commit"] = {
            "returncode": result.returncode,
            "stdout": result.stdout.strip(),
            "stderr": result.stderr.strip(),
        }
        success = result.returncode == 0
        return {
            "success": success,
            "message": message,
            "results": results,
        }
    except subprocess.TimeoutExpired:
        return {"success": False, "error": "git commit timed out"}
    except Exception as e:
        return {"success": False, "error": f"git commit failed: {e}"}


def close_session(
    messages: List[Dict[str, Any]],
    repo_path: str = "",
    session_log_path: Optional[str] = None,
    skip_commit: bool = False,
    commit_message: str = "",
) -> Dict[str, Any]:
    """
    Run the full session closing protocol.

    Steps:
      1. Summarize session messages
      2. Write log to ~/.metamatrix/sessions/YYYY-MM-DD.md
      3. Git commit the session log (unless skip_commit)

    Args:
        messages: List of session messages
        repo_path: Path to git repo for auto-commit
        session_log_path: Custom log file path
        skip_commit: If True, skip the git commit step
        commit_message: Custom commit message

    Returns:
        dict with summary, log_path, and commit result
    """
    # Step 1: Summarize
    summary = summarize_session(messages)

    # Step 2: Write log
    log_path = write_session_log(summary, path=session_log_path)

    result = {
        "summary_length": len(summary),
        "log_path": log_path,
        "commit": None,
    }

    # Step 3: Git commit
    if not skip_commit and repo_path:
        commit_msg = commit_message or (
            f"session: auto-log {datetime.now().strftime('%Y-%m-%d %H:%M')}\n\n"
            f"Metamatrix session closer protocol.\n"
            f"Messages: {len(messages)}"
        )
        commit_result = git_commit_session(
            repo_path=repo_path,
            message=commit_msg,
            session_log_path=log_path,
        )
        result["commit"] = commit_result

    return result
